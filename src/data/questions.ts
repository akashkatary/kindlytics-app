// Generates calibrated CB priorities for each question
export function getQuestionCbPriorities(
  seq: number,
  primaryPriority: PriorityLevel,
  primaryCbId: string
): CbPriorities {
  const cbIndex = COMPOSITE_BEHAVIOURS.findIndex(c => c.id === primaryCbId);
  const activeIdx = cbIndex >= 0 ? cbIndex : ((seq - 1) % 18);

  const prioAt = (targetIdx1Based: number): number => {
    const targetIdx0Based = targetIdx1Based - 1;
    if (targetIdx0Based === activeIdx) return PRIORITY_DEFAULT_VALUES[primaryPriority];
    const diff = Math.abs(targetIdx0Based - activeIdx);
    if (diff === 1 || diff === 17) return 4;
    if (diff === 2 || diff === 16) return 3;
    if (diff === 3 || diff === 15) return 2;
    return 1;
  };

  return {
    visPrio: prioAt(1),
    infPrio: prioAt(2),
    decPrio: prioAt(3),
    undPrio: prioAt(4),
    pePrio: prioAt(5),
    reasPrio: prioAt(6),
    openPrio: prioAt(7),
    listPrio: prioAt(8),
    artPrio: prioAt(9),
    saPrio: prioAt(10),
    empPrio: prioAt(11),
    collabPrio: prioAt(12),
    psPrio: prioAt(13),
    adaptPrio: prioAt(14),
    creatPrio: prioAt(15),
    initPrio: prioAt(16),
    compPrio: prioAt(17),
    qualPrio: prioAt(18),
  };
}

export const INITIAL_QUESTIONS: Question[] = SEED_DATA.map((seed, index) => {
  const cb = COMPOSITE_BEHAVIOURS.find(c => c.id === seed.cbId) || COMPOSITE_BEHAVIOURS[0];
  const sc = SUMMARY_CHARACTERISTICS.find(s => s.id === cb.parentId) || SUMMARY_CHARACTERISTICS[0];
  const kc = KEY_CHARACTERISTICS.find(k => k.id === sc.parentId) || KEY_CHARACTERISTICS[0];
  const seq = index + 1;

  // Ques2 is Inactive, Negative orientation, matching user baseline
  const active = seq === 2 ? false : true;
  const orientation = seq === 2 ? 'NEGATIVE' : seed.orientation;
  const positiveResponse = seq === 2 ? 'NO' : seed.positiveResponse;

  return {
    questionId: `Q${String(seq).padStart(3, '0')}`,
    sequence: seq,
    questionName: seed.name,
    selfQuestionText: seed.self,
    peerQuestionText: seed.peer,
    keyCharacteristicId: kc.id,
    keyCharacteristicName: kc.name,
    summaryCharacteristicId: sc.id,
    summaryCharacteristicName: sc.name,
    compositeBehaviourId: cb.id,
    compositeBehaviourName: cb.name,
    behaviouralAntonym: seed.antonym,
    orientation,
    positiveResponse,
    priority: seed.priority,
    weight: PRIORITY_DEFAULT_VALUES[seed.priority],
    active,
    responseType: 'BINARY',
    cbPriorities: getQuestionCbPriorities(seq, seed.priority, cb.id),
  };
});
